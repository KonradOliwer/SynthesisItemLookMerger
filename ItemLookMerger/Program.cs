using System.IO.Abstractions;
using ItemLookMerger.Core;
using ItemLookMerger.Core.Mo2;
using Mutagen.Bethesda;
using Mutagen.Bethesda.Skyrim;
using Mutagen.Bethesda.Synthesis;
using Noggog;

namespace ItemLookMerger;

public static class Program
{
    internal const string SettingsFileName = "settings.json";

    public static async Task<int> Main(string[] args)
    {
        using var logFile = ConsoleLogFile.StartIfRequested(ref args);
        try
        {
            return await SynthesisPipeline.Instance
                .SetAutogeneratedSettings("Settings", SettingsFileName, out Lazy<Settings> lazySettings)
                .AddPatch<ISkyrimMod, ISkyrimModGetter>(
                    state => RunPatch(state, lazySettings.Value, new WindowsMo2Environment(), new FileSystem()))
                .SetTypicalOpen(GameRelease.SkyrimSE, "ItemLookMerger.esp")
                .Run(args);
        }
        catch (Exception ex) when (logFile != null)
        {
            logFile.WriteToFileOnly(ex.ToString());
            throw;
        }
    }

    /// <summary>Maps the Synthesis state and settings onto the core run; a run failure is printed, then rethrown so Synthesis fails the run.</summary>
    internal static void RunPatch(
        IPatcherState<ISkyrimMod, ISkyrimModGetter> state, Settings settings, IMo2Environment mo2Environment, IFileSystem fileSystem)
    {
        var loadOrder = state.LoadOrder.ListedOrder
            .Where(listing => listing.ModKey != state.PatchMod.ModKey)
            .Select(listing => listing.Mod)
            .WhereNotNull()
            .ToList();
        // The full listing, not the trimmed LoadOrder: it also holds the plugins below the patch's line. The patch may be listed and appended.
        var enabledPlugins = state.RawLoadOrder
            .Where(listing => listing.Enabled && listing.ModKey != state.PatchMod.ModKey)
            .Select(listing => listing.ModKey)
            .Distinct()
            .ToList();
        var merging = settings.ContentMerging ?? new ContentMergingSettings();
        var options = new MergeOptions(
            settings.PluginsToForward ?? [],
            settings.ForwardNames,
            settings.VerboseLogging,
            merging.AllowMerging,
            merging.ForwardFolderName,
            settings.InCaseOfTypeDiscrepancy);
        try
        {
            PatchRun.Run(new RunInputs(
                loadOrder, enabledPlugins, state.PatchMod, state.DataFolderPath.Path, options, mo2Environment, fileSystem,
                new ConsoleLog(settings.VerboseLogging)));
        }
        catch (RunFailedException ex)
        {
            Console.Error.WriteLine(ex.Message);
            throw;
        }
    }
}
