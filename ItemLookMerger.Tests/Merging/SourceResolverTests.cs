using System.IO.Abstractions.TestingHelpers;
using ItemLookMerger.Core;
using ItemLookMerger.Core.Merging;
using ItemLookMerger.Core.Mo2;
using ItemLookMerger.Tests.Support;
using Mutagen.Bethesda.Plugins;
using Mutagen.Bethesda.Plugins.Records;
using Mutagen.Bethesda.Skyrim;

namespace ItemLookMerger.Tests.Merging;

public class SourceResolverTests
{
    /// <summary>Hands out prepared plugins by file name instead of reading files.</summary>
    private sealed class FakeOpener(params SkyrimMod[] plugins) : IPluginOpener
    {
        public List<string> Opened { get; } = [];

        public ISkyrimModGetter Open(string path)
        {
            Opened.Add(path);
            return plugins.Single(plugin => plugin.ModKey.FileName == Path.GetFileName(path));
        }
    }

    /// <summary>Fails like Mutagen does on a truncated plugin file.</summary>
    private sealed class CorruptOpener : IPluginOpener
    {
        public ISkyrimModGetter Open(string path) => throw new EndOfStreamException("Unexpected end of file.");
    }

    private const string ForwardFolderName = "OUTPUT ItemLookMerger";

    /// <summary>
    /// The fixture's mod list as MO2 writes it, with the look mod "Relics of Skyrim" disabled on top, and a BOM, CRLF and trailing
    /// spaces added. Priorities: Relics of Skyrim 4, Better Iron Armor 3, Stats Overhaul 2, Disabled Looks 1, Base Fixes 0.
    /// </summary>
    private const string UserModList =
        "\uFEFF-Relics of Skyrim  \r\n# This file was automatically generated by Mod Organizer.\r\n+Better Iron Armor\r\n+Stats Overhaul \r\n"
        + "-Weapons_separator\r\n*Unmanaged: Dawnguard\r\n-Disabled Looks\r\n+Base Fixes\r\n";

    private readonly TestPlugins _plugins = new();
    private readonly TestLog _log = new();
    private readonly MockFileSystem _fileSystem = Mo2Fixtures.Portable();

    public SourceResolverTests() =>
        _fileSystem.AddFile(Path.Combine(Mo2Fixtures.PortableProfile, "modlist.txt"), new MockFileData(UserModList));

    private IReadOnlyList<LookSource> Resolve(IPluginOpener opener, bool allowMerging, params string?[] mods) =>
        SourceResolver.Resolve(
            mods,
            _plugins.LoadOrder(),
            _plugins.Patch.ModKey,
            Mo2Instance.Load(_fileSystem, Mo2Fixtures.PortableFolder),
            opener,
            allowMerging,
            ForwardFolderName,
            _fileSystem,
            _log);

    private void AddPluginFile(string mod, string plugin) =>
        _fileSystem.AddFile(Path.Combine(Mo2Fixtures.PortableMods, mod, plugin), new MockFileData([]));

    [Fact]
    public void A_disabled_mods_esm_is_read_from_its_folder_with_the_mods_priority()
    {
        var look = _plugins.LookPlugin("Relics of Skyrim.esm", "Relic");
        AddPluginFile("Relics of Skyrim", "Relics of Skyrim.esm");
        var opener = new FakeOpener(look);

        var source = Assert.Single(Resolve(opener, allowMerging: true, "Relics of Skyrim"));

        Assert.False(source.InLoadOrder);
        Assert.Equal("Relics of Skyrim", source.ModName);
        Assert.Equal(@"C:\MO2Portable\mods\Relics of Skyrim\Relics of Skyrim.esm", Assert.Single(opener.Opened));
        Assert.Equal(4, source.ModPriority);
        Assert.Contains(_log.Infos, line => line.Contains("(disabled)"));
    }

    [Fact]
    public void A_mod_contributes_every_plugin_at_its_top_and_none_from_subfolders()
    {
        var main = _plugins.LookPlugin("Relics of Skyrim.esm", "Relic");
        var extra = _plugins.LookPlugin("Relics - Extra.esl", "Extra");
        AddPluginFile("Relics of Skyrim", "Relics of Skyrim.esm");
        AddPluginFile("Relics of Skyrim", "Relics - Extra.esl");
        AddPluginFile("Relics of Skyrim", @"00 Optional\Ignored.esp");
        AddPluginFile("Relics of Skyrim", "readme.txt");
        var opener = new FakeOpener(main, extra);

        var sources = Resolve(opener, allowMerging: true, "Relics of Skyrim");

        Assert.Equal(["Relics - Extra.esl", "Relics of Skyrim.esm"], sources.Select(source => source.ModKey.FileName.String));
        Assert.All(sources, source => Assert.Equal("Relics of Skyrim", source.ModName));
        Assert.Equal(2, opener.Opened.Count);
    }

    [Fact]
    public void A_plugin_in_the_load_order_is_used_as_loaded_and_keeps_the_listed_mod()
    {
        // A higher-priority mod has a copy of the plugin too; the listed mod still names the source.
        AddPluginFile("Better Iron Armor", "Stats.esp");

        var source = Assert.Single(Resolve(new FakeOpener(), allowMerging: true, "Stats Overhaul"));

        Assert.True(source.InLoadOrder);
        Assert.Same(_plugins.Stats, source.Mod);
        Assert.Equal("Stats Overhaul", source.ModName);
        Assert.Equal(2, source.ModPriority);
    }

    [Fact]
    public void Names_are_trimmed_matched_ignoring_case_and_deduplicated()
    {
        AddPluginFile("Relics of Skyrim", "Relics of Skyrim.esm");
        var opener = new FakeOpener(_plugins.LookPlugin("Relics of Skyrim.esm", "Relic"));

        var source = Assert.Single(Resolve(opener, allowMerging: true, "  relics of skyrim ", "", null, "   ", "RELICS OF SKYRIM"));

        Assert.Equal("Relics of Skyrim", source.ModName);
        Assert.Single(opener.Opened);
    }

    [Fact]
    public void Unknown_mods_fail_the_run_in_one_error_with_suggestions()
    {
        AddPluginFile("Relics of Skyrim", "Relics of Skyrim.esm");
        AddPluginFile("Unlisted Folder", "Unlisted.esp");
        var opener = new FakeOpener();

        var ex = Assert.Throws<RunFailedException>(() => Resolve(opener, allowMerging: true, "Relics of Skyrm", "Relics", "Zzz Nothing Alike", "Unlisted Folder", "Base Fixes"));

        Assert.Empty(opener.Opened);
        Assert.Contains("5 entries of \"Mods to forward\" cannot be used", ex.Message);
        Assert.Contains("\"Relics of Skyrm\" is no mod of profile \"My Profile\"", ex.Message);
        Assert.Contains("Did you mean \"Relics of Skyrim\"?", ex.Message);
        var nothingAlike = Assert.Single(ex.Message.Split('\n'), line => line.Contains("\"Zzz Nothing Alike\" is no mod"));
        Assert.DoesNotContain("Did you mean", nothingAlike);
        Assert.Contains("\"Unlisted Folder\" is a folder in C:\\MO2Portable\\mods but not in modlist.txt", ex.Message);
        Assert.Contains("\"Base Fixes\" is in modlist.txt of profile \"My Profile\", but its folder", ex.Message);
    }

    [Fact]
    public void Suggestions_rank_substrings_before_typos_and_stop_at_three()
    {
        var instance = Mo2Instance.Load(_fileSystem, Mo2Fixtures.PortableFolder);

        Assert.Equal(["Relics of Skyrim"], instance.SuggestMods("relics"));
        Assert.Equal(["Stats Overhaul"], instance.SuggestMods("Stats Overhual"));
        Assert.Empty(instance.SuggestMods("Zzz Nothing Alike"));
        Assert.Equal(3, instance.SuggestMods("s").Count);
    }

    [Theory]
    [InlineData(@"..\Relics of Skyrim")]
    [InlineData(@"C:\MO2Portable\mods\Relics of Skyrim")]
    [InlineData("Relics/Skyrim")]
    public void A_name_that_is_not_a_plain_folder_name_fails_the_run(string name)
    {
        var ex = Assert.Throws<RunFailedException>(() => Resolve(new FakeOpener(), allowMerging: true, name));
        Assert.Contains("is not a plain MO2 mod folder name", ex.Message);
    }

    [Fact]
    public void The_forward_folder_cannot_be_a_look_source()
    {
        var ex = Assert.Throws<RunFailedException>(() => Resolve(new FakeOpener(), allowMerging: true, "output itemlookmerger"));
        Assert.Contains("is the forward folder", ex.Message);
    }

    [Fact]
    public void A_mod_without_a_top_level_plugin_fails_the_run()
    {
        AddPluginFile("Relics of Skyrim", @"00 Core\Relics of Skyrim.esm");

        var ex = Assert.Throws<RunFailedException>(() => Resolve(new FakeOpener(), allowMerging: true, "Relics of Skyrim"));
        Assert.Contains("\"Relics of Skyrim\" has no plugin (.esp, .esm or .esl) at its top level", ex.Message);
    }

    [Fact]
    public void One_plugin_in_two_listed_mods_fails_the_run()
    {
        AddPluginFile("Relics of Skyrim", "Stats.esp");

        var ex = Assert.Throws<RunFailedException>(() => Resolve(new FakeOpener(), allowMerging: true, "Stats Overhaul", "Relics of Skyrim"));
        Assert.Contains("Stats.esp is in both \"Stats Overhaul\" and \"Relics of Skyrim\"", ex.Message);
    }

    [Fact]
    public void The_patch_itself_in_a_listed_mod_fails_the_run()
    {
        AddPluginFile("Relics of Skyrim", _plugins.Patch.ModKey.FileName);

        var ex = Assert.Throws<RunFailedException>(() => Resolve(new FakeOpener(), allowMerging: true, "Relics of Skyrim"));
        Assert.Contains("own output", ex.Message);
    }

    [Fact]
    public void A_corrupt_plugin_file_fails_the_run()
    {
        AddPluginFile("Relics of Skyrim", "Look.esp");

        var ex = Assert.Throws<RunFailedException>(() => Resolve(new CorruptOpener(), allowMerging: true, "Relics of Skyrim"));
        Assert.Contains("cannot be read", ex.Message);
    }

    [Fact]
    public void A_disabled_plugin_with_its_masters_loaded_is_read_from_its_mod()
    {
        var look = _plugins.LookPlugin("Look.esp", "Fancy");
        look.ModHeader.MasterReferences.Add(new MasterReference { Master = _plugins.Base.ModKey });
        AddPluginFile("Relics of Skyrim", "Look.esp");

        var source = Assert.Single(Resolve(new FakeOpener(look), allowMerging: true, "Relics of Skyrim"));
        Assert.False(source.InLoadOrder);
    }

    [Fact]
    public void A_plugin_with_masters_outside_the_load_order_fails_the_run()
    {
        var look = _plugins.LookPlugin("Look.esp", "Fancy");
        look.ModHeader.MasterReferences.Add(new MasterReference { Master = ModKey.FromFileName("Missing.esm") });
        AddPluginFile("Relics of Skyrim", "Look.esp");

        var ex = Assert.Throws<RunFailedException>(() => Resolve(new FakeOpener(look), allowMerging: true, "Relics of Skyrim"));
        Assert.Contains("Missing.esm", ex.Message);
    }

    [Fact]
    public void Without_merging_a_plugin_outside_the_load_order_fails_the_run()
    {
        AddPluginFile("Relics of Skyrim", "Look.esp");
        var opener = new FakeOpener();

        var ex = Assert.Throws<RunFailedException>(() => Resolve(opener, allowMerging: false, "Relics of Skyrim"));
        Assert.Empty(opener.Opened);
        Assert.Contains("Turn on content merging", ex.Message);
    }
}
